export const DEFAULT_IMAGE = 'https://images.unsplash.com/photo-1519501025264-65ba15a82390?auto=format&fit=crop&w=1200&q=80';
export const DEFAULT_TAGS = ['Travel', 'Explore'];

// Для карточек городов на странице Destinations (меньшего размера)
export const CARD_IMAGE_SIZE = 'w=600&q=80';
export const DETAIL_IMAGE_SIZE = 'w=1200&q=80';

// Функция для получения изображения нужного размера
export const getCityImageBySize = (city, isDetail = false) => {
  const baseImage = CITY_IMAGES[city] || DEFAULT_IMAGE;
  // Если это уже статический URL без параметров размера, возвращаем как есть
  if (!baseImage.includes('unsplash.com') || !baseImage.includes('auto=format')) {
    return baseImage;
  }
  
  // Заменяем параметры размера
  const size = isDetail ? DETAIL_IMAGE_SIZE : CARD_IMAGE_SIZE;
  return baseImage.replace(/w=\d+&q=\d+/, size);
}; 